#ifndef __CRC32_H
#define __CRC32_H

#include "stm32f4xx.h"

/* ================================================================== *
 * 硬件 CRC32 (STM32F4 CRC 外设)
 * 算法: CRC-32/MPEG-2
 *   多项式: 0x04C11DB7, 初始值: 0xFFFFFFFF
 *   无输入/输出反转, 逐 32-bit 字处理 (小端)
 * ================================================================== */

/* 打开 CRC 外设时钟并复位计算单元 (初始化时调用一次) */
void Crc32_Init(void);

/* 复位计算单元: 每次新固件校验前调用, 从初始值重新累计 */
void Crc32_Reset(void);

/* 计算方法: 向 CRC->DR 逐个写入 32-bit 字, 全部写完后读 CRC->DR
 * 即为结果。具体用法见 flash.c 的 Flash_CalcAppCrc32()。
 * 注意: 外设要求按字访问, 固件长度按 4 字节对齐补齐后计算。 */

#endif /* __CRC32_H */
